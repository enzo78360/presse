// Presse : historique du presse-papiers dans la barre des menus.
import AppKit
import Carbon.HIToolbox
import ServiceManagement

/// Les 50 derniers textes copiés, enregistrés sur le disque.
final class History {
    private(set) var items: [String] = []
    private(set) var pinned: [String] = []
    private let limit = 50
    private let url: URL

    private struct Stored: Codable { var items: [String]; var pinned: [String] }

    init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Presse", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        url = dir.appendingPathComponent("historique.json")
        if let data = try? Data(contentsOf: url), let s = try? JSONDecoder().decode(Stored.self, from: data) {
            items = s.items
            pinned = s.pinned
        }
    }

    func add(_ text: String) {
        if pinned.contains(text) { return }
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
        save()
    }

    func togglePin(_ text: String) {
        if let i = pinned.firstIndex(of: text) {
            pinned.remove(at: i)
            items.insert(text, at: 0)
        } else {
            items.removeAll { $0 == text }
            pinned.append(text)
        }
        save()
    }

    func clear() {
        items = []
        save()
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(Stored(items: items, pinned: pinned)) else { return }
        try? data.write(to: url, options: .atomic)
        // Le fichier peut contenir des informations personnelles : lisible par toi seul.
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}

final class App: NSObject, NSApplicationDelegate, NSMenuDelegate {
    let status = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
    let history = History()
    var lastChange = NSPasteboard.general.changeCount
    var paused = false
    var hotKey: EventHotKeyRef?

    // Types posés par les gestionnaires de mots de passe et les apps qui ne veulent pas être enregistrées.
    let ignored: Set<NSPasteboard.PasteboardType> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
    ].reduce(into: []) { $0.insert(NSPasteboard.PasteboardType($1)) }

    func applicationDidFinishLaunching(_ notification: Notification) {
        status.button?.image = NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "Presse")
        let menu = NSMenu()
        menu.delegate = self
        status.menu = menu
        Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        registerHotKey()
    }

    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }
        if (pb.types ?? []).contains(where: ignored.contains) { return }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        history.add(text)
    }

    // MARK: Menu

    func menuNeedsUpdate(_ menu: NSMenu) {
        menu.removeAllItems()

        if !history.pinned.isEmpty {
            menu.addItem(header("Épinglés"))
            for (i, text) in history.pinned.enumerated() {
                menu.addItem(entry(text, tag: 1000 + i, key: ""))
            }
            menu.addItem(.separator())
        }

        menu.addItem(header(paused ? "Historique (en pause)" : "Historique"))
        if history.items.isEmpty {
            let empty = NSMenuItem(title: "Rien de copié pour l'instant", action: nil, keyEquivalent: "")
            empty.isEnabled = false
            menu.addItem(empty)
        }
        for (i, text) in history.items.enumerated() {
            menu.addItem(entry(text, tag: i, key: i < 9 ? "\(i + 1)" : ""))
        }

        menu.addItem(.separator())
        let tip = NSMenuItem(title: "⌥ clic : épingler / désépingler", action: nil, keyEquivalent: "")
        tip.isEnabled = false
        menu.addItem(tip)
        menu.addItem(action(paused ? "Reprendre l'enregistrement" : "Mettre en pause", #selector(togglePause)))
        menu.addItem(action("Effacer l'historique", #selector(clearHistory)))
        let login = action("Ouvrir au démarrage", #selector(toggleLogin))
        login.state = SMAppService.mainApp.status == .enabled ? .on : .off
        menu.addItem(login)
        menu.addItem(.separator())
        menu.addItem(action("Quitter Presse", #selector(NSApplication.terminate(_:)), key: "q", target: NSApp))
    }

    func header(_ title: String) -> NSMenuItem {
        if #available(macOS 14, *) { return .sectionHeader(title: title) }
        let item = NSMenuItem(title: title, action: nil, keyEquivalent: "")
        item.isEnabled = false
        return item
    }

    func entry(_ text: String, tag: Int, key: String) -> NSMenuItem {
        let item = NSMenuItem(title: preview(text), action: #selector(pick(_:)), keyEquivalent: key)
        item.keyEquivalentModifierMask = []
        item.tag = tag
        item.target = self
        item.toolTip = String(text.prefix(600))
        return item
    }

    func action(_ title: String, _ sel: Selector, key: String = "", target: AnyObject? = nil) -> NSMenuItem {
        let item = NSMenuItem(title: title, action: sel, keyEquivalent: key)
        item.target = target ?? self
        return item
    }

    func preview(_ text: String) -> String {
        let line = text.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }.joined(separator: " ⏎ ")
        return line.count > 60 ? String(line.prefix(58)) + "…" : line
    }

    @objc func pick(_ sender: NSMenuItem) {
        let text = sender.tag >= 1000 ? history.pinned[sender.tag - 1000] : history.items[sender.tag]
        if NSEvent.modifierFlags.contains(.option) {
            history.togglePin(text)
            return
        }
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChange = pb.changeCount
        history.add(text)
    }

    @objc func togglePause() { paused.toggle() }
    @objc func clearHistory() { history.clear() }

    @objc func toggleLogin() {
        do {
            if SMAppService.mainApp.status == .enabled { try SMAppService.mainApp.unregister() }
            else { try SMAppService.mainApp.register() }
        } catch {
            let alert = NSAlert()
            alert.messageText = "Impossible de modifier l'ouverture au démarrage"
            alert.informativeText = "Place Presse dans le dossier Applications puis réessaie.\n\(error.localizedDescription)"
            alert.runModal()
        }
    }

    // MARK: Raccourci global ⌃⌘V

    func registerHotKey() {
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, ctx in
            let app = Unmanaged<App>.fromOpaque(ctx!).takeUnretainedValue()
            DispatchQueue.main.async { app.status.button?.performClick(nil) }
            return noErr
        }, 1, &spec, Unmanaged.passUnretained(self).toOpaque(), nil)
        let id = EventHotKeyID(signature: OSType(0x5052_5353), id: 1)  // « PRSS »
        RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(cmdKey | controlKey), id, GetApplicationEventTarget(), 0, &hotKey)
    }
}

let app = NSApplication.shared
let delegate = App()
app.delegate = delegate
app.setActivationPolicy(.accessory)
app.run()
